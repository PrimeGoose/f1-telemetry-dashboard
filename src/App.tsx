import { useEffect, useMemo, useState } from 'react'
import { Controls } from './components/Controls'
import { LapTable } from './components/LapTable'
import { LiveGauges } from './components/LiveGauges'
import { TelemetryChart, type ChartSeries } from './components/TelemetryChart'
import { TrackMap } from './components/TrackMap'
import { usePlayback } from './hooks/usePlayback'
import { bestLap, deltaSeries, lapSamples, lapStartTime, sampleAt, sessionDuration } from './lib/replay'
import { ReplayFileSource, type TelemetrySource } from './lib/source'
import type { Session } from './lib/types'

const DEFAULT_SOURCE: TelemetrySource = new ReplayFileSource(`${import.meta.env.BASE_URL}sample/session.json`)

export default function App({ source = DEFAULT_SOURCE, autoplay = true }: { source?: TelemetrySource; autoplay?: boolean }) {
  const [session, setSession] = useState<Session | null>(null)
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    let cancelled = false
    source
      .load()
      .then((s) => !cancelled && setSession(s))
      .catch((e: unknown) => !cancelled && setError(e instanceof Error ? e.message : String(e)))
    return () => {
      cancelled = true
    }
  }, [source])

  return (
    <div className="mx-auto max-w-7xl p-4">
      <header className="mb-4 flex flex-wrap items-center justify-between gap-2">
        <div>
          <h1 className="text-xl font-semibold">F1 Telemetry Dashboard</h1>
          <p className="text-xs text-slate-400">Replay viewer – speed, throttle, brake, gear, RPM, lap times and track position</p>
        </div>
        <span className="rounded-full border border-amber-400/40 bg-amber-400/10 px-3 py-1 text-xs text-amber-300">
          SAMPLE DATA · synthetic, not real telemetry
        </span>
      </header>
      {error ? (
        <p role="alert" className="rounded border border-red-500/40 bg-red-500/10 p-3 text-sm text-red-300">
          {error}
        </p>
      ) : !session ? (
        <p className="text-sm text-slate-400">Loading replay…</p>
      ) : (
        <Dashboard session={session} autoplay={autoplay} />
      )}
      <footer className="mt-6 text-xs text-slate-500">
        All values are generated by <code>scripts/generate-sample.ts</code>. No game, team or driver data is used.
      </footer>
    </div>
  )
}

function Dashboard({ session, autoplay }: { session: Session; autoplay: boolean }) {
  const duration = sessionDuration(session)
  const playback = usePlayback(duration, autoplay)
  const current = sampleAt(session, playback.time)
  const lap = current.lap

  const best = useMemo(() => bestLap(session.laps), [session.laps])
  const lapData = useMemo(() => lapSamples(session, lap), [session, lap])
  const refData = useMemo(() => (best ? lapSamples(session, best.lap) : []), [session, best])
  const lapStart = lapData[0]?.t ?? 0
  const trail = useMemo(() => lapData.filter((s) => s.t <= current.t), [lapData, current.t])
  const delta = useMemo(() => deltaSeries(lapData, refData), [lapData, refData])

  const xDomain: [number, number] = [0, session.circuit.lengthM]
  const line = (data: typeof lapData, f: (s: (typeof lapData)[number]) => number): [number, number][] =>
    data.map((s) => [s.distance, f(s)])
  const showRef = best !== undefined && best.lap !== lap

  const speed: ChartSeries[] = [
    ...(showRef ? [{ label: `Best (L${best.lap})`, color: '#c026d3', muted: true, points: line(refData, (s) => s.speed) }] : []),
    { label: `Lap ${lap}`, color: '#38bdf8', points: line(lapData, (s) => s.speed) },
  ]
  const pedals: ChartSeries[] = [
    { label: 'Throttle', color: '#22c55e', points: line(lapData, (s) => s.throttle) },
    { label: 'Brake', color: '#ef4444', points: line(lapData, (s) => s.brake) },
  ]
  const rpm: ChartSeries[] = [{ label: 'RPM', color: '#f59e0b', points: line(lapData, (s) => s.rpm) }]
  const deltaMax = Math.max(0.5, ...delta.map((d) => Math.abs(d.delta)))

  return (
    <div className="grid gap-4 lg:grid-cols-[minmax(0,5fr)_minmax(0,7fr)]">
      <div className="space-y-4">
        <Controls
          playback={playback}
          duration={duration}
          laps={session.laps.map((l) => l.lap)}
          currentLap={lap}
          onLap={(l) => playback.seek(lapStartTime(session, l))}
        />
        <LiveGauges sample={current} />
        <TrackMap outline={session.circuit.outline} current={current} trail={trail} name={session.circuit.name} />
        <LapTable laps={session.laps} currentLap={lap} currentLapTime={current.t - lapStart} onSelect={(l) => playback.seek(lapStartTime(session, l))} />
      </div>
      <div className="space-y-3">
        <TelemetryChart title="Speed" unit="km/h" series={speed} xDomain={xDomain} yDomain={[0, 350]} cursorX={current.distance} height={150} />
        <TelemetryChart title="Throttle / brake" unit="%" series={pedals} xDomain={xDomain} yDomain={[0, 100]} cursorX={current.distance} />
        <TelemetryChart title="Engine" unit="rpm" series={rpm} xDomain={xDomain} yDomain={[4000, 13000]} cursorX={current.distance} />
        <TelemetryChart
          title="Time delta vs best lap"
          unit="s"
          series={[{ label: `Lap ${lap}`, color: '#a78bfa', points: delta.map((d) => [d.distance, d.delta]) }]}
          xDomain={xDomain}
          yDomain={[-deltaMax, deltaMax]}
          cursorX={current.distance}
        />
      </div>
    </div>
  )
}
